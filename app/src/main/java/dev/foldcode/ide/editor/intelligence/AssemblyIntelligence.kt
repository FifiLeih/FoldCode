internal fun isAssemblySource(path: String): Boolean =
    path.substringAfterLast('.', "").lowercase() in setOf("s", "asm")

/** ARM/RISC-V completion using the board selected by the Pico project. */
internal fun assemblyCompletionItems(projectSources: Map<String, String>): List<CompletionItem> {
    val common = assemblyDirectives + assemblyCommonInstructions
    if (projectSources.isEmpty()) return common
    val architecture = if (picoBoard(projectSources).chip == PicoChip.Rp2350RiscV) {
        riscvAssemblyItems
    } else {
        armAssemblyItems
    }
    val labels = projectSources
        .filterKeys(::isAssemblySource)
        .values
        .asSequence()
        .flatMap { source ->
            Regex("(?m)^\\s*([A-Za-z_.$][A-Za-z0-9_.$]*):").findAll(source).map { it.groupValues[1] }
        }
        .distinct()
        .map { CompletionItem(it, it, "Project assembly label") }
        .toList()
    return (labels + architecture + common).distinctBy { it.label.lowercase() }
}

private fun assemblyWords(words: String, detail: String): List<CompletionItem> =
    words.split(Regex("\\s+")).filter(String::isNotBlank).map { CompletionItem(it, it, detail) }

private val assemblyDirectives = listOf(
